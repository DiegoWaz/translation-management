export const flagFromCountryCode = (code: string): string => {
  const cc = code.toUpperCase()
  if (!/^[A-Z]{2}$/.test(cc)) return '🏳️'
  return [...cc].map(ch => String.fromCodePoint(127397 + ch.charCodeAt(0))).join('')
}

export const countryName = (code: string, locale: string): string => {
  try {
    return new Intl.DisplayNames([locale], { type: 'region' }).of(code.toUpperCase()) ?? code.toUpperCase()
  } catch {
    return code.toUpperCase()
  }
}

export type CountryOption = { code: string; name: string; flag: string }

export const listCountries = (locale: string): CountryOption[] => {
  return WORLD_COUNTRY_CODES
    .map(code => ({
      code,
      name: countryName(code, locale),
      flag: flagFromCountryCode(code),
    }))
    .sort((a, b) => a.name.localeCompare(b.name, locale))
}

export const countryByFlag = (flag: string, locale: string): CountryOption | undefined =>
  listCountries(locale).find(c => c.flag === flag)

export const countryByCode = (code: string, locale: string): CountryOption | undefined => {
  const cc = code.toUpperCase()
  if (!WORLD_COUNTRY_CODES.includes(cc)) return undefined
  return { code: cc, name: countryName(cc, locale), flag: flagFromCountryCode(cc) }
}

export const filterCountries = (query: string, locale: string): CountryOption[] => {
  const q = query.trim().toLowerCase()
  const all = listCountries(locale)
  if (!q) return all
  return all.filter(c =>
    c.name.toLowerCase().includes(q) || c.code.toLowerCase().includes(q),
  )
}
